import type { FolderRule } from '../database/schema';

export interface SieveOptions {
  readonly notifyScript: string;
}

// Sieve string literals take backslash and double quote escapes and nothing else.
function quote(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

// :matches also treats * and ? as wildcards. Escaping happens in one pass and the intended
// wildcard is appended outside it, or escaping the value would escape the wildcard too.
function quoteMatch(value: string, { prefix = '', suffix = '' } = {}): string {
  return `"${prefix}${value.replace(/([\\"*?])/g, '\\$1')}${suffix}"`;
}

function headerFor(field: string): string | null {
  switch (field) {
    case 'sender':
      return 'from';
    case 'subject':
      return 'subject';
    case 'recipient':
      return 'to';
    default:
      return null;
  }
}

function condition(rule: FolderRule): string | null {
  const header = headerFor(rule.conditionField);

  if (header === null) {
    return null;
  }

  const name = quote(header);

  switch (rule.conditionOperator) {
    case 'contains':
      return `header :contains ${name} ${quote(rule.conditionValue)}`;
    case 'equals':
      return `header :is ${name} ${quote(rule.conditionValue)}`;
    case 'starts_with':
      return `header :matches ${name} ${quoteMatch(rule.conditionValue, { suffix: '*' })}`;
    case 'ends_with':
      return `header :matches ${name} ${quoteMatch(rule.conditionValue, { prefix: '*' })}`;
    default:
      return null;
  }
}

// Each branch that stops has to report for itself. The pipe used to sit only at the end,
// after every rule's `stop`, so a message a rule filed away was never reported at all - it
// left the inbox and never appeared in the folder either.
function body(rule: FolderRule, notify: string): string[] | null {
  switch (rule.action) {
    case 'move_to':
      return rule.targetFolder === null
        ? null
        : [
            `fileinto ${quote(rule.targetFolder)};`,
            `${notifyCall(notify, rule.targetFolder)};`,
            'stop;',
          ];
    // No stop: it keeps going and the pipe at the end reports it in INBOX.
    case 'mark_read':
      return ['setflag "\\\\Seen";'];
    // Nothing is stored locally in either case, so there is nothing to report.
    case 'forward':
      return [`redirect ${quote(rule.conditionValue)};`, 'stop;'];
    case 'discard':
      return ['discard;', 'stop;'];
    default:
      return null;
  }
}

// The folder rides as an argument because the pipe program runs with a cleared environment
// and otherwise has no idea where the message was filed.
function notifyCall(script: string, folder: string): string {
  return `pipe :copy ${quote(script)} [${quote(folder)}]`;
}

// Fixed order: spam, then user rules, then notification. Regenerated whole on every change,
// so the script can never drift from the table it came from.
export function generateSieve(rules: readonly FolderRule[], options: SieveOptions): string {
  const lines: string[] = [
    'require ["copy", "fileinto", "imap4flags", "vnd.dovecot.pipe"];',
    '',
    '# Generated by stampyx-api. Edits here are overwritten.',
    '',
    'if header :contains "X-Spam-Flag" "YES" {',
    '    fileinto "Spam";',
    `    ${notifyCall(options.notifyScript, 'Spam')};`,
    '    stop;',
    '}',
    '',
  ];

  for (const rule of [...rules]
    .filter((rule) => rule.active)
    .sort((a, b) => a.position - b.position)) {
    const test = condition(rule);
    const action = body(rule, options.notifyScript);

    if (test === null || action === null) {
      continue;
    }

    lines.push(`if ${test} {`, ...action.map((line) => `    ${line}`), '}', '');
  }

  lines.push(`${notifyCall(options.notifyScript, 'INBOX')};`, '');

  return lines.join('\n');
}
